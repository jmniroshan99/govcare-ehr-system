package lk.gov.health.govcare.laboratory;

import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.Image;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import lk.gov.health.govcare.common.SqlSupport;
import lk.gov.health.govcare.security.GovCarePrincipal;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;

@Service
public class BloodReportPdfService {
    private final BloodReportService reports;
    private final SqlSupport sql;

    public BloodReportPdfService(BloodReportService reports, SqlSupport sql) {
        this.reports = reports;
        this.sql = sql;
    }

    public Report generate(GovCarePrincipal actor, String id) {
        Map<String, Object> report = reports.get(actor, id);
        Map<String, Object> hospital = sql.required("select name,code,address,phone,email from hospitals where id=:id",
                Map.of("id", actor.hospitalId()), "Hospital not found.");
        try {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            Document doc = new Document(PageSize.A4, 28, 28, 30, 30);
            PdfWriter writer = PdfWriter.getInstance(doc, out);
            doc.open();

            Color brand = new Color(15, 74, 110);
            Color light = new Color(238, 247, 250);
            Font govcare = new Font(Font.HELVETICA, 20, Font.BOLD, brand);
            Font hospitalFont = new Font(Font.HELVETICA, 10, Font.BOLD, Color.DARK_GRAY);
            Font tiny = new Font(Font.HELVETICA, 7.5f, Font.NORMAL, Color.DARK_GRAY);
            Font title = new Font(Font.HELVETICA, 11, Font.BOLD, Color.BLACK);
            Font header = new Font(Font.HELVETICA, 7.5f, Font.BOLD, Color.BLACK);
            Font body = new Font(Font.HELVETICA, 8f, Font.NORMAL, Color.BLACK);
            Font bold = new Font(Font.HELVETICA, 8f, Font.BOLD, Color.BLACK);

            PdfPTable top = new PdfPTable(new float[]{1.3f, 1f});
            top.setWidthPercentage(100);
            PdfPCell brandCell = noBorder();
            Image logo = loadLogo();
            if (logo != null) brandCell.addElement(logo);
            brandCell.addElement(new Paragraph("GovCare EHR", govcare));
            brandCell.addElement(new Paragraph(Objects.toString(hospital.get("name"), "Government Hospital"), hospitalFont));
            brandCell.addElement(new Paragraph(Objects.toString(hospital.get("address"), ""), tiny));
            top.addCell(brandCell);
            PdfPCell contact = noBorder();
            contact.setHorizontalAlignment(Element.ALIGN_RIGHT);
            Paragraph c = new Paragraph();
            c.setAlignment(Element.ALIGN_RIGHT);
            c.setFont(tiny);
            c.add("Email: " + Objects.toString(hospital.get("email"), "Not recorded") + "\n");
            c.add("Phone: " + Objects.toString(hospital.get("phone"), "Not recorded") + "\n");
            c.add("Hospital Code: " + Objects.toString(hospital.get("code"), "-") + "\n");
            c.add("Secure laboratory report generated by GovCare EHR");
            contact.addElement(c);
            top.addCell(contact);
            doc.add(top);
            doc.add(new Paragraph(" ", tiny));

            PdfPTable patient = new PdfPTable(new float[]{0.8f, 1.5f, 0.9f, 1.4f});
            patient.setWidthPercentage(100);
            patient.getDefaultCell().setPadding(3);
            addPair(patient, "Name", report.get("patient_name"), header, body, light);
            addPair(patient, "Patient ID", report.get("patient_no"), header, body, light);
            addPair(patient, "Age / Gender", displayAgeGender(report), header, body, light);
            addPair(patient, "Report ID", report.get("report_number"), header, body, light);
            addPair(patient, "Referred By", first(report.get("referred_by"), "Self / Not recorded"), header, body, light);
            addPair(patient, "Collection Date", formatDate(report.get("collected_at")), header, body, light);
            addPair(patient, "Phone No.", first(report.get("phone"), "Not recorded"), header, body, light);
            addPair(patient, "Report Date", formatDate(firstObject(report.get("reported_at"), report.get("updated_at"))), header, body, light);
            if (report.get("ward_name") != null || report.get("bed_code") != null) {
                addPair(patient, "Ward / Bed", Objects.toString(report.get("ward_name"), "-") + " / " + Objects.toString(report.get("bed_code"), "-"), header, body, light);
                addPair(patient, "Sample No.", report.get("sample_number"), header, body, light);
            }
            doc.add(patient);
            doc.add(new Paragraph(" ", tiny));

            Paragraph h1 = new Paragraph("HAEMATOLOGY", title); h1.setAlignment(Element.ALIGN_CENTER); doc.add(h1);
            Paragraph h2 = new Paragraph("COMPLETE BLOOD COUNT (CBC)", title); h2.setAlignment(Element.ALIGN_CENTER); doc.add(h2);
            doc.add(new Paragraph(" ", tiny));

            PdfPTable table = new PdfPTable(new float[]{2.9f, 1.1f, 1.35f, 1.1f, 0.7f});
            table.setWidthPercentage(100);
            for (String col : List.of("TEST DESCRIPTION", "RESULT", "REF. RANGE", "UNIT", "FLAG")) table.addCell(headCell(col, header, light));

            @SuppressWarnings("unchecked") List<Map<String, Object>> values = (List<Map<String, Object>>) report.get("results");
            String lastCategory = null;
            for (Map<String, Object> row : values) {
                String category = Objects.toString(row.get("category"), "CBC");
                if (!Objects.equals(category, lastCategory)) {
                    PdfPCell section = new PdfPCell(new Phrase(category, bold));
                    section.setColspan(5); section.setPadding(4); section.setBackgroundColor(new Color(247, 247, 247));
                    table.addCell(section); lastCategory = category;
                }
                String flag = Objects.toString(row.get("abnormal_flag"), "");
                Font valueFont = Set.of("L", "H", "C").contains(flag) ? bold : body;
                table.addCell(dataCell(Objects.toString(row.get("test_name"), ""), body));
                table.addCell(dataCell(formatNumber(row.get("result_value")), valueFont));
                table.addCell(dataCell(range(row), body));
                table.addCell(dataCell(Objects.toString(row.get("unit"), ""), body));
                table.addCell(dataCell(flagText(flag), Set.of("L", "H", "C").contains(flag) ? bold : body));
            }
            doc.add(table);

            doc.add(new Paragraph(" ", tiny));
            PdfPTable remarks = new PdfPTable(1); remarks.setWidthPercentage(100);
            PdfPCell remarksCell = new PdfPCell(); remarksCell.setPadding(6);
            remarksCell.addElement(new Paragraph("Interpretation / Remarks", bold));
            remarksCell.addElement(new Paragraph(Objects.toString(report.get("interpretation"), "No interpretation recorded."), body));
            remarks.addCell(remarksCell); doc.add(remarks);
            doc.add(new Paragraph(" ", tiny));

            PdfPTable signatures = new PdfPTable(new float[]{1f, 1f, 1f}); signatures.setWidthPercentage(100);
            signatures.addCell(signature("Prepared By", report.get("prepared_by_name"), body, bold));
            signatures.addCell(signature("Verified By", report.get("verified_by_name"), body, bold));
            signatures.addCell(signature("Report Generated", formatDate(report.get("updated_at")), body, bold));
            doc.add(signatures);

            doc.add(new Paragraph(" ", tiny));
            Paragraph legend = new Paragraph("Flag legend: N = Normal | L = Low | H = High | C = Critical. Reference ranges are configured by the laboratory and may vary by age, sex and hospital policy.", tiny);
            doc.add(legend);
            Paragraph footer = new Paragraph("GovCare EHR secure laboratory report | Page " + writer.getPageNumber(), tiny);
            footer.setAlignment(Element.ALIGN_RIGHT); doc.add(footer);
            doc.close();

            String safePatient = Objects.toString(report.get("patient_no"), "patient").replaceAll("[^A-Za-z0-9_-]", "_");
            String date = java.time.LocalDate.now().toString();
            return new Report(out.toByteArray(), "CBC_" + report.get("report_number") + "_" + safePatient + "_" + date + ".pdf");
        } catch (Exception e) {
            throw new IllegalStateException("Unable to generate CBC PDF report.", e);
        }
    }


    private static Image loadLogo() {
        for (Path path : List.of(Path.of("../public/ministry-health-logo.png"), Path.of("public/ministry-health-logo.png"))) {
            try {
                if (Files.isRegularFile(path)) {
                    Image image = Image.getInstance(Files.readAllBytes(path));
                    image.scaleToFit(52, 52);
                    return image;
                }
            } catch (Exception ignored) {
                // The report remains valid with GovCare text branding if a logo file is unavailable.
            }
        }
        return null;
    }

    private static PdfPCell noBorder() { PdfPCell c = new PdfPCell(); c.setBorder(Rectangle.NO_BORDER); c.setPadding(2); return c; }
    private static PdfPCell headCell(String text, Font font, Color background) { PdfPCell c = new PdfPCell(new Phrase(text, font)); c.setPadding(4); c.setBackgroundColor(background); return c; }
    private static PdfPCell dataCell(String text, Font font) { PdfPCell c = new PdfPCell(new Phrase(text, font)); c.setPadding(4); return c; }
    private static void addPair(PdfPTable table, String label, Object value, Font header, Font body, Color background) { PdfPCell h = dataCell(label, header); h.setBackgroundColor(background); table.addCell(h); table.addCell(dataCell(Objects.toString(value, "Not recorded"), body)); }
    private static PdfPCell signature(String label, Object value, Font body, Font bold) { PdfPCell c = new PdfPCell(); c.setPadding(6); c.addElement(new Paragraph(label, bold)); c.addElement(new Paragraph(Objects.toString(value, "Not recorded"), body)); c.addElement(new Paragraph("\nSignature: __________________", body)); return c; }
    private static String displayAgeGender(Map<String, Object> report) { return Objects.toString(report.get("age_years"), "-") + " / " + Objects.toString(report.get("gender"), "-"); }
    private static String flagText(String f) { return switch (f) { case "L" -> "LOW (L)"; case "H" -> "HIGH (H)"; case "C" -> "CRITICAL (C)"; case "N" -> "N"; default -> ""; }; }
    private static String range(Map<String, Object> row) { Object min = row.get("min_reference"), max = row.get("max_reference"); if (min == null && max == null) return "-"; return formatNumber(min) + " - " + formatNumber(max); }
    private static String formatNumber(Object value) { if (value == null) return ""; try { BigDecimal n = new BigDecimal(String.valueOf(value)); return n.stripTrailingZeros().toPlainString(); } catch (Exception e) { return String.valueOf(value); } }
    private static Object firstObject(Object a, Object b) { return a == null ? b : a; }
    private static String first(Object a, String fallback) { String s = Objects.toString(a, "").trim(); return s.isEmpty() ? fallback : s; }
    private static String formatDate(Object value) { if (value == null) return "Not recorded"; try { return OffsetDateTime.parse(String.valueOf(value)).format(DateTimeFormatter.ofPattern("dd/MM/yyyy hh:mm a")); } catch (Exception ignored) { return String.valueOf(value); } }

    public record Report(byte[] bytes, String filename) {}
}
